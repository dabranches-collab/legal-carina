test('tradução falhada bloqueia emissão; PDF/Word e reimpressão da versão', async ({ page }, info) => {
  await client(page)
  await page.getByRole('button', { name: 'Preparar nota', exact: true }).click()
  const dialog = await modal(page, 'Preparar nota de honorários')
  await dialog.getByRole('combobox', { name: 'Idioma do documento', exact: true }).selectOption('fr')
  await dialog.getByText('Ensaiar falha de tradução', { exact: true }).click()
  await dialog.getByRole('checkbox', { name: 'Simular indisponibilidade da tradução EN/FR' }).check()
  await dialog.getByRole('button', { name: 'Emitir exemplo PDF' }).click()
  await expect(dialog.getByRole('alert')).toContainText('emissão foi bloqueada')
  await dialog.getByRole('checkbox', { name: 'Simular indisponibilidade da tradução EN/FR' }).uncheck()
  await dialog.getByRole('button', { name: 'Pré-visualizar sem guardar' }).click()
  await expect(dialog.getByRole('region', { name: 'Pré-visualização do documento' })).toContainText('Réunion de suivi')
  await page.screenshot({ path: `output/workflow-qa/screenshots/${info.project.name}-traducao-fr.png`, fullPage: true })
  const pdfPromise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Emitir exemplo PDF' }).click()
  const pdf = await pdfPromise; expect(pdf.suggestedFilename()).toMatch(/fr\.pdf$/)
  await pdf.saveAs(`output/workflow-qa/${info.project.name}-nota-fr.pdf`)
  await expect(dialog).not.toBeVisible()
  await page.getByRole('navigation', { name: 'Áreas da ficha do cliente' }).getByRole('button', { name: 'Financeiro e documentos', exact: true }).click()
  await expect(page.getByText('Réunion de suivi et analyse de documents.', { exact: true })).toBeVisible()
  const wordPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Guardar Word', exact: true }).click()
  const word = await wordPromise; expect(word.suggestedFilename()).toMatch(/fr\.docx$/)
  await word.saveAs(`output/workflow-qa/${info.project.name}-nota-fr.docx`)
  const reprint = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Guardar PDF', exact: true }).click()
  expect((await reprint).suggestedFilename()).toBe(pdf.suggestedFilename())
})

