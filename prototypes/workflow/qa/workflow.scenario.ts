import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const clientName = 'Cliente Alfa — DEMO'
let external: string[]
let pageErrors: string[]
async function menu(page: Page, label: string) {
  if (await page.getByRole('button', { name: 'Abrir navegação', exact: true }).isVisible()) await page.getByRole('button', { name: 'Abrir navegação', exact: true }).click()
  await page.getByRole('complementary', { name: 'Navegação principal' }).getByRole('button', { name: label, exact: false }).click()
}
async function client(page: Page) {
  await menu(page, 'Clientes')
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: clientName, exact: true }) }).getByRole('button', { name: 'Abrir ficha', exact: true }).click()
}
async function view(page: Page, fila: string) { await menu(page, 'Financeiro'); await page.getByRole('navigation', { name: 'Áreas do Financeiro' }).getByRole('button', { name: fila, exact: true }).click() }
async function modal(page: Page, name: string) { const dialog = page.getByRole('dialog', { name, exact: true }); await expect(dialog).toBeVisible(); return dialog }

test.beforeEach(async ({ page }) => {
  external = []; pageErrors = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.route('**/*', async route => {
    const url = route.request().url()
    if (url.startsWith('http://127.0.0.1:5175/') || url.startsWith('blob:') || url.startsWith('data:')) await route.continue()
    else { external.push(url); await route.abort() }
  })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Resumo', exact: true })).toBeVisible()
})
test.afterEach(async () => { expect(external, 'O protótipo não pode tentar contactar serviços externos').toEqual([]); expect(pageErrors, 'Sem erros JavaScript no percurso').toEqual([]) })

test('cinco menus, cinco áreas da ficha, temas e largura da página', async ({ page }, info) => {
  await mkdir('output/workflow-qa/screenshots', { recursive: true })
  for (const dark of [false, true]) {
    if (dark) await page.getByRole('button', { name: 'Activar modo escuro' }).click()
    for (const name of ['Resumo', 'Clientes', 'Trabalho', 'Financeiro', 'Notas']) {
      await menu(page, name)
      await expect(page.getByRole('heading', { level: 1 })).toHaveText(name)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
      await page.screenshot({ path: `output/workflow-qa/screenshots/${info.project.name}-${name}-${dark ? 'dark' : 'light'}.png`, fullPage: true })
    }
    await client(page)
    const tabs = page.getByRole('navigation', { name: 'Áreas da ficha do cliente' })
    await expect(tabs.getByRole('button')).toHaveCount(5)
    for (const name of ['Resumo', 'Dados', 'Trabalho', 'Contratos', 'Financeiro e documentos']) {
      await tabs.getByRole('button', { name, exact: true }).click()
      await expect(tabs.getByRole('button', { name, exact: true })).toHaveAttribute('aria-current', 'page')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
      await page.screenshot({ path: `output/workflow-qa/screenshots/${info.project.name}-cliente-${name.replaceAll(' ', '-')}-${dark ? 'dark' : 'light'}.png`, fullPage: true })
    }
  }
})

